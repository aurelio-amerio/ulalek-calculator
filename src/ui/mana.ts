const SYMBOL = /\{([0-9]|C|T)\}|\n/g;

/** One symbol as a gray circle with the glyph inside, like on a printed card. */
export function manaSymbol(key: string): HTMLElement {
  const glyph = GLYPHS[key];
  if (!glyph) throw new Error(`Unknown mana symbol {${key}}`);
  const span = document.createElement('span');
  span.className = `mana mana--${key.toLowerCase()}`;
  span.setAttribute('role', 'img');
  span.setAttribute('aria-label', glyph.label);
  const svg = document.createElementNS(SVG_NS, 'svg');
  svg.setAttribute('viewBox', '0 0 32 32');
  svg.setAttribute('aria-hidden', 'true');
  const path = document.createElementNS(SVG_NS, 'path');
  path.setAttribute('fill', 'currentColor');
  path.setAttribute('d', glyph.path);
  svg.append(path);
  span.append(svg);
  return span;
}

/**
 * Turns card text into nodes: `{0}`..`{9}`, `{C}` and `{T}` become symbols, newlines become line
 * breaks, anything else (including symbols with no glyph, such as `{W}`) stays text.
 */
export function manaText(text: string): Node[] {
  const out: Node[] = [];
  let last = 0;
  for (const m of text.matchAll(SYMBOL)) {
    if (m.index > last) out.push(document.createTextNode(text.slice(last, m.index)));
    if (m[0] === '\n') out.push(document.createElement('br'));
    else if (m[1] in GLYPHS) out.push(manaSymbol(m[1]));
    else out.push(document.createTextNode(m[0]));
    last = m.index + m[0].length;
  }
  if (last < text.length) out.push(document.createTextNode(text.slice(last)));
  return out;
}
